/**
 * Event Planning Domain Models & Strict Type Definitions
 * Certified Special Events Professional (CSEP) Domain Standard
 */

export type EventVertical = 'wedding' | 'birthday' | 'community';

export type Currency = 'INR' | 'USD';

export type CityTier = 'tier1' | 'tier2' | 'tier3' | 'destination';

export type SettingType = 'indoor' | 'outdoor' | 'hybrid';

export type FeasibilityLevel = 'optimal' | 'warning' | 'critical';

export type VendorCriticality = 'High' | 'Medium' | 'Low';

export type VendorStatus = 'Not Started' | 'Shortlisted' | 'Contract Sent' | 'Booked';

/** Priority weighting distribution between core event pillars */
export interface PriorityWeights {
  venue: number;
  catering: number;
  decor: number;
  entertainment: number;
  logistics: number;
}

/** User inputs gathered during smart onboarding */
export interface EventPlanInput {
  vertical: EventVertical;
  eventName: string;
  guestCount: number;
  eventDate: string; // YYYY-MM-DD
  durationHours: number;
  cityTier: CityTier;
  cityName: string;
  totalBudget: number;
  currency: Currency;
  priorityWeights: PriorityWeights;
  themeKeywords: string[];
  dietaryRequirements: string[];
  culturalCustoms: string;
  setting: SettingType;
  contingencyPercentage: number; // 8% - 12% standard
}

/** Individual budget line item with dynamic locking & rebalancing */
export interface BudgetItem {
  id: string;
  category: 'venue' | 'catering' | 'decor' | 'entertainment' | 'logistics' | 'contingency';
  name: string;
  allocatedAmount: number;
  percentage: number;
  locked: boolean;
  costSavingTip: string;
  notes: string;
  subItems?: {
    name: string;
    estimatedCost: number;
    priority: 'must-have' | 'nice-to-have';
  }[];
}

/** Feasibility and budget analysis generated by deterministic engine */
export interface FeasibilityAssessment {
  level: FeasibilityLevel;
  perGuestSpend: number;
  minRecommendedSpend: number;
  optimalSpend: number;
  message: string;
  details: string[];
}

/** Milestone item for macro reverse-engineered timeline */
export interface TimelineMilestone {
  id: string;
  timeframe: string; // e.g. "6 Months Out", "30 Days Out", "Sprint Day 3"
  title: string;
  description: string;
  dueDate: string;
  daysRemaining: number;
  category: string;
  completed: boolean;
  critical: boolean;
}

/** Hour-by-hour day-of execution schedule */
export interface RunOfShowItem {
  id: string;
  time: string; // e.g. "09:00 AM"
  activity: string;
  owner: string;
  location: string;
  notes: string;
}

/** Smart vendor tracking with hidden cost warnings & vetting questions */
export interface VendorItem {
  id: string;
  category: string;
  vendorRole: string;
  criticality: VendorCriticality;
  status: VendorStatus;
  estimatedBudget: number;
  hiddenCostWarnings: string[];
  defaultInquiryPrompt: string;
  vettingQuestions: string[];
}

/** Color swatch definition */
export interface ColorSwatch {
  name: string;
  hex: string;
}

/** Menu course item */
export interface MenuItem {
  course: string;
  name: string;
  description: string;
  dietaryTags: string[];
}

/** Personalized concept cards */
export interface ThemeConcept {
  id: string;
  name: string;
  tagline: string;
  description: string;
  colorPalette: ColorSwatch[];
  decorElements: string[];
  signatureMenu: MenuItem[];
  engagementActivities: string[];
}

/** Crisis / What-If simulation presets */
export interface CrisisScenario {
  id: string;
  title: string;
  description: string;
  type: 'guest_spike' | 'rain_forecast' | 'budget_cut' | 'vendor_cancel';
  impactDescription: string;
}

/** Complete aggregated Event Plan data model */
export interface FullEventPlan {
  id: string;
  createdAt: string;
  lastUpdated: string;
  source: 'ai' | 'preset' | 'modified';
  input: EventPlanInput;
  summary: {
    title: string;
    tagline: string;
    perGuestSpend: number;
    feasibility: FeasibilityAssessment;
    contingencyAmount: number;
  };
  budget: {
    totalBudget: number;
    currency: Currency;
    contingencyPercentage: number;
    items: BudgetItem[];
  };
  timeline: {
    isSprintMode: boolean;
    daysRemaining: number;
    milestones: TimelineMilestone[];
    runOfShow: RunOfShowItem[];
  };
  vendors: VendorItem[];
  ideation: {
    concepts: ThemeConcept[];
    activeConceptId?: string;
  };
}

/** LLM Response structure returned by Gemini Structured Output */
export interface GeminiStructuredPlanResponse {
  title: string;
  tagline: string;
  budgetItems: {
    category: 'venue' | 'catering' | 'decor' | 'entertainment' | 'logistics' | 'contingency';
    name: string;
    percentage: number;
    costSavingTip: string;
    notes: string;
    subItems?: {
      name: string;
      estimatedCost: number;
      priority: 'must-have' | 'nice-to-have';
    }[];
  }[];
  milestones: {
    timeframe: string;
    title: string;
    description: string;
    category: string;
    critical: boolean;
    daysOffsetFromEvent: number; // e.g. -180 for 6 months before, 0 for day of
  }[];
  runOfShow: {
    time: string;
    activity: string;
    owner: string;
    location: string;
    notes: string;
  }[];
  vendors: {
    category: string;
    vendorRole: string;
    criticality: VendorCriticality;
    percentageOfBudget: number;
    hiddenCostWarnings: string[];
    defaultInquiryPrompt: string;
    vettingQuestions: string[];
  }[];
  concepts: {
    name: string;
    tagline: string;
    description: string;
    colorPalette: { name: string; hex: string }[];
    decorElements: string[];
    signatureMenu: { course: string; name: string; description: string; dietaryTags: string[] }[];
    engagementActivities: string[];
  }[];
}
